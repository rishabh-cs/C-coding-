// Loop in C language-




#include <stdio.h>

// 1.for Loop

//code-

int main() {
    for(int i=0;i<=10;i++){
        printf("%d \n",i);
  }
    return 0;
}

// 2.while Loop

//code-

int main(){
    int i=0;
    while(i<=10){
        printf("%d\n",i);
         i++;   
    }
}

// 3.do-while Loop

//code-

int main(){
    int i=0;
    do{
        printf("%d \n",i);
        i++;
    }while(i<=10);
}
